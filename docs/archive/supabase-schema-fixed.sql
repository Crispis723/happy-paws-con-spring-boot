-- IMPORTANTE:
-- Este archivo reemplaza el SQL anterior que tenía dos
-- incompatibilidades principales:
--   1) appointments.fecha -> appointments.fecha_hora
--   2) appointments.veterinario_id ahora referencia users.id
-- También incluye password_reset_tokens y un esquema de
-- permissions compatible con DataInitializer/Permission.java.
