DROP TABLE IF EXISTS compras CASCADE;
DROP TABLE IF EXISTS comprobante_series CASCADE;
DROP TABLE IF EXISTS comprobante_tipos CASCADE;
DROP TABLE IF EXISTS productos CASCADE;
DROP TABLE IF EXISTS afectacion_tipos CASCADE;
DROP TABLE IF EXISTS units CASCADE;
DROP TABLE IF EXISTS historial_mascotas CASCADE;
DROP TABLE IF EXISTS appointments CASCADE;
DROP TABLE IF EXISTS pets CASCADE;
DROP TABLE IF EXISTS clientes CASCADE;
DROP TABLE IF EXISTS proveedores CASCADE;
DROP TABLE IF EXISTS user_roles CASCADE;
DROP TABLE IF EXISTS roles CASCADE;
DROP TABLE IF EXISTS users CASCADE;
DROP TABLE IF EXISTS documento_tipos CASCADE;
DROP TABLE IF EXISTS system_settings CASCADE;

-- ============================================================
-- 1. TIPOS DE DOCUMENTO
-- ============================================================
CREATE TABLE documento_tipos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    descripcion VARCHAR(150) NOT NULL
);
CREATE INDEX idx_documento_tipos_codigo ON documento_tipos(codigo);

-- ============================================================
-- 2. ROLES
-- ============================================================
CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE,
    description VARCHAR(150),
    enabled BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_roles_name ON roles(name);
CREATE INDEX idx_roles_enabled ON roles(enabled);

-- ============================================================
-- 3. USERS
-- ============================================================
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_users_email ON users(email);

-- ============================================================
-- 4. USER ROLES
-- ============================================================
-- user_id es PRIMARY KEY (no solo parte de una PK compuesta con role_id):
-- esto es lo que garantiza a nivel de base de datos que un usuario
-- nunca pueda tener más de un rol asignado al mismo tiempo.
CREATE TABLE user_roles (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id)
        REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_user_roles_role FOREIGN KEY (role_id)
        REFERENCES roles(id) ON DELETE CASCADE
);
CREATE INDEX idx_user_roles_role_id ON user_roles(role_id);

-- ============================================================
-- 5. MODULES (CATÁLOGO DEL RBAC)
-- Cada permiso pertenece obligatoriamente a un módulo.
-- ============================================================
CREATE TABLE modules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(150),
    icon VARCHAR(100),
    route VARCHAR(255),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    display_order INT NOT NULL DEFAULT 0
);
CREATE INDEX idx_modules_code ON modules(code);
CREATE INDEX idx_modules_enabled ON modules(enabled);
CREATE INDEX idx_modules_display_order ON modules(display_order);

-- ============================================================
-- 6. PERMISSIONS
-- Entidad normalizada: código único + módulo obligatorio + acción.
-- ============================================================
CREATE TABLE permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id BIGINT NOT NULL,
    code VARCHAR(100) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(150),
    action VARCHAR(30) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_permissions_module FOREIGN KEY (module_id)
        REFERENCES modules(id) ON DELETE RESTRICT,
    CONSTRAINT ck_permissions_action CHECK (action IN ('VIEW','CREATE','UPDATE','DELETE','EXPORT','ASSIGN'))
);
CREATE INDEX idx_permissions_module_id ON permissions(module_id);
CREATE INDEX idx_permissions_code ON permissions(code);
CREATE INDEX idx_permissions_action ON permissions(action);
CREATE INDEX idx_permissions_enabled ON permissions(enabled);

-- ============================================================
-- 7. ROLE PERMISSIONS
-- ============================================================
CREATE TABLE role_permissions (
    role_id BIGINT NOT NULL,
    permission_id BIGINT NOT NULL,
    PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fk_role_permissions_role FOREIGN KEY (role_id)
        REFERENCES roles(id) ON DELETE CASCADE,
    CONSTRAINT fk_role_permissions_permission FOREIGN KEY (permission_id)
        REFERENCES permissions(id) ON DELETE CASCADE
);
CREATE INDEX idx_role_permissions_role_id ON role_permissions(role_id);
CREATE INDEX idx_role_permissions_permission_id ON role_permissions(permission_id);

-- ============================================================
-- 8. PASSWORD RESET TOKENS
-- ============================================================
CREATE TABLE password_reset_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token VARCHAR(255) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL,
    expiry_date TIMESTAMP NOT NULL,
    used BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_password_reset_tokens_user FOREIGN KEY (user_id)
        REFERENCES users(id) ON DELETE CASCADE
);
CREATE INDEX idx_password_reset_tokens_user_id ON password_reset_tokens(user_id);
CREATE INDEX idx_password_reset_tokens_expiry_date ON password_reset_tokens(expiry_date);

-- ============================================================
-- 9. CLIENTES
-- ============================================================
CREATE TABLE clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_tipo_codigo VARCHAR(20) NOT NULL,
    numero_documento VARCHAR(20) NOT NULL UNIQUE,
    razon_social VARCHAR(150) NOT NULL,
    direccion VARCHAR(255),
    telefono VARCHAR(30),
    email VARCHAR(150),
    CONSTRAINT fk_clientes_documento_tipo FOREIGN KEY (documento_tipo_codigo)
        REFERENCES documento_tipos(codigo)
);
CREATE INDEX idx_clientes_numero_documento ON clientes(numero_documento);
CREATE INDEX idx_clientes_documento_tipo ON clientes(documento_tipo_codigo);
CREATE INDEX idx_clientes_razon_social ON clientes(razon_social);

-- ============================================================
-- 10. PROVEEDORES
-- ============================================================
CREATE TABLE proveedores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_tipo_codigo VARCHAR(20) NOT NULL,
    numero_documento VARCHAR(20) NOT NULL UNIQUE,
    razon_social VARCHAR(150) NOT NULL,
    direccion VARCHAR(255),
    telefono VARCHAR(30),
    email VARCHAR(150),
    CONSTRAINT fk_proveedores_documento_tipo FOREIGN KEY (documento_tipo_codigo)
        REFERENCES documento_tipos(codigo)
);
CREATE INDEX idx_proveedores_numero_documento ON proveedores(numero_documento);
CREATE INDEX idx_proveedores_documento_tipo ON proveedores(documento_tipo_codigo);
CREATE INDEX idx_proveedores_razon_social ON proveedores(razon_social);

-- ============================================================
-- 11. MASCOTAS
-- ============================================================
CREATE TABLE pets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    especie VARCHAR(80) NOT NULL,
    raza VARCHAR(80),
    edad INT,
    cliente_id BIGINT NOT NULL,
    CONSTRAINT fk_pets_cliente FOREIGN KEY (cliente_id)
        REFERENCES clientes(id) ON DELETE CASCADE
);
CREATE INDEX idx_pets_cliente_id ON pets(cliente_id);
CREATE INDEX idx_pets_nombre ON pets(nombre);

-- ============================================================
-- 12. CITAS
-- IMPORTANTE: coincide exactamente con Appointment.java.
-- veterinario_id referencia users porque Appointment.veterinario
-- es de tipo User, no una entidad Veterinario.
-- ============================================================
CREATE TABLE appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id BIGINT NOT NULL,
    cliente_id BIGINT NOT NULL,
    veterinario_id BIGINT,
    fecha_hora TIMESTAMP NOT NULL,
    motivo VARCHAR(255) NOT NULL,
    CONSTRAINT fk_appointments_pet FOREIGN KEY (pet_id)
        REFERENCES pets(id) ON DELETE CASCADE,
    CONSTRAINT fk_appointments_cliente FOREIGN KEY (cliente_id)
        REFERENCES clientes(id) ON DELETE CASCADE,
    CONSTRAINT fk_appointments_veterinario FOREIGN KEY (veterinario_id)
        REFERENCES users(id) ON DELETE SET NULL
);
CREATE INDEX idx_appointments_pet_id ON appointments(pet_id);
CREATE INDEX idx_appointments_cliente_id ON appointments(cliente_id);
CREATE INDEX idx_appointments_veterinario_id ON appointments(veterinario_id);
CREATE INDEX idx_appointments_fecha_hora ON appointments(fecha_hora);

-- ============================================================
-- 13. HISTORIAL DE MASCOTAS
-- ============================================================
CREATE TABLE historial_mascotas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id BIGINT NOT NULL,
    appointment_id BIGINT,
    titulo VARCHAR(150) NOT NULL,
    detalle VARCHAR(1500) NOT NULL,
    diagnostico VARCHAR(500),
    tratamiento VARCHAR(500),
    fecha_registro DATE NOT NULL,
    fecha_expiracion DATE NOT NULL,
    archivo_original VARCHAR(255),
    archivo_guardado VARCHAR(255),
    archivo_tipo VARCHAR(120),
    archivo_tamanio BIGINT,
    CONSTRAINT fk_historial_pet FOREIGN KEY (pet_id)
        REFERENCES pets(id) ON DELETE CASCADE,
    CONSTRAINT fk_historial_appointment FOREIGN KEY (appointment_id)
        REFERENCES appointments(id) ON DELETE SET NULL
);
CREATE INDEX idx_historial_pet_id ON historial_mascotas(pet_id);
CREATE INDEX idx_historial_fecha_registro ON historial_mascotas(fecha_registro);
CREATE INDEX idx_historial_fecha_expiracion ON historial_mascotas(fecha_expiracion);

-- ============================================================
-- 14. UNIDADES
-- ============================================================
CREATE TABLE units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    descripcion VARCHAR(150) NOT NULL
);
CREATE INDEX idx_units_codigo ON units(codigo);

-- ============================================================
-- 15. TIPOS DE AFECTACIÓN
-- ============================================================
CREATE TABLE afectacion_tipos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    descripcion VARCHAR(255) NOT NULL,
    letra VARCHAR(1) NOT NULL,
    porcentaje DECIMAL(5,2) NOT NULL
);
CREATE INDEX idx_afectacion_tipos_codigo ON afectacion_tipos(codigo);

-- ============================================================
-- 16. PRODUCTOS
-- ============================================================
CREATE TABLE productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    descripcion VARCHAR(500),
    unidad_id BIGINT NOT NULL,
    afectacion_tipo_id BIGINT NOT NULL,
    precio_unitario DECIMAL(12,2) NOT NULL,
    stock INT NOT NULL DEFAULT 0,
    imagen VARCHAR(255),
    CONSTRAINT fk_productos_unidad FOREIGN KEY (unidad_id)
        REFERENCES units(id) ON DELETE RESTRICT,
    CONSTRAINT fk_productos_afectacion FOREIGN KEY (afectacion_tipo_id)
        REFERENCES afectacion_tipos(id) ON DELETE RESTRICT
);
CREATE INDEX idx_productos_codigo ON productos(codigo);
CREATE INDEX idx_productos_nombre ON productos(nombre);
CREATE INDEX idx_productos_unidad_id ON productos(unidad_id);
CREATE INDEX idx_productos_afectacion_tipo_id ON productos(afectacion_tipo_id);

-- ============================================================
-- 17. TIPOS DE COMPROBANTE
-- ============================================================
CREATE TABLE comprobante_tipos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    descripcion VARCHAR(150) NOT NULL
);
CREATE INDEX idx_comprobante_tipos_codigo ON comprobante_tipos(codigo);

-- ============================================================
-- 18. SERIES DE COMPROBANTES
-- ============================================================
CREATE TABLE comprobante_series (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comprobante_tipo_codigo VARCHAR(20) NOT NULL,
    serie VARCHAR(10) NOT NULL,
    correlativo INT NOT NULL,
    CONSTRAINT uk_comprobante_tipo_serie UNIQUE (comprobante_tipo_codigo, serie),
    CONSTRAINT fk_comprobante_series_tipo FOREIGN KEY (comprobante_tipo_codigo)
        REFERENCES comprobante_tipos(codigo)
);
CREATE INDEX idx_comprobante_series_tipo ON comprobante_series(comprobante_tipo_codigo);
CREATE INDEX idx_comprobante_series_serie ON comprobante_series(serie);

-- ============================================================
-- 19. COMPRAS
-- ============================================================
CREATE TABLE compras (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero VARCHAR(20) NOT NULL UNIQUE,
    fecha DATE NOT NULL,
    proveedor_id BIGINT NOT NULL,
    comprobante_tipo_codigo VARCHAR(20) NOT NULL,
    forma_pago VARCHAR(30) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'registrada',
    total DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    CONSTRAINT fk_compras_proveedor FOREIGN KEY (proveedor_id)
        REFERENCES proveedores(id) ON DELETE RESTRICT,
    CONSTRAINT fk_compras_comprobante_tipo FOREIGN KEY (comprobante_tipo_codigo)
        REFERENCES comprobante_tipos(codigo)
);
CREATE INDEX idx_compras_numero ON compras(numero);
CREATE INDEX idx_compras_fecha ON compras(fecha);
CREATE INDEX idx_compras_proveedor_id ON compras(proveedor_id);
CREATE INDEX idx_compras_estado ON compras(estado);

-- ============================================================
-- 20. VENTAS
-- ============================================================
CREATE TABLE ventas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero VARCHAR(20) NOT NULL UNIQUE,
    fecha DATE NOT NULL,
    cliente_id BIGINT NOT NULL,
    forma_pago VARCHAR(30) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'registrada',
    total DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    CONSTRAINT fk_ventas_cliente FOREIGN KEY (cliente_id)
        REFERENCES clientes(id) ON DELETE RESTRICT
);
CREATE INDEX idx_ventas_numero ON ventas(numero);
CREATE INDEX idx_ventas_fecha ON ventas(fecha);
CREATE INDEX idx_ventas_cliente_id ON ventas(cliente_id);
CREATE INDEX idx_ventas_estado ON ventas(estado);

-- ============================================================
-- 21. CONFIGURACIÓN
-- ============================================================
CREATE TABLE system_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    setting_key VARCHAR(100) NOT NULL UNIQUE,
    setting_value VARCHAR(255) NOT NULL
);
CREATE INDEX idx_system_settings_key ON system_settings(setting_key);

