    ON appointments(fecha_hora);

CREATE INDEX idx_historial_pet_id
    ON historial_mascotas(pet_id);

CREATE INDEX idx_historial_appointment_id
    ON historial_mascotas(appointment_id);

CREATE INDEX idx_historial_fecha_registro
    ON historial_mascotas(fecha_registro);

CREATE INDEX idx_productos_unidad_id
    ON productos(unidad_id);

CREATE INDEX idx_productos_afectacion_tipo_id
