DROP TABLE IF EXISTS comprobante_series CASCADE;
DROP TABLE IF EXISTS comprobante_tipos CASCADE;
DROP TABLE IF EXISTS documento_tipos CASCADE;
DROP TABLE IF EXISTS system_settings CASCADE;
DROP TABLE IF EXISTS users CASCADE;

-- ============================================================
-- 2. TABLAS BASE
-- ============================================================

-- User.java
CREATE TABLE users (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE
);

-- Role.java
CREATE TABLE roles (
    id_rol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE,
    description VARCHAR(150),
    enabled BOOLEAN NOT NULL DEFAULT TRUE
);

-- DocumentoTipo.java
CREATE TABLE documento_tipos (
    id_documento_tipo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    descripcion VARCHAR(150) NOT NULL
);

-- ComprobanteTipo.java
CREATE TABLE comprobante_tipos (
    id_comprobante_tipo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    descripcion VARCHAR(150) NOT NULL
);

-- Unidad.java (tabla física "units")
CREATE TABLE units (
    id_unidad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    descripcion VARCHAR(150) NOT NULL
);

-- AfectacionTipo.java
CREATE TABLE afectacion_tipos (
    id_afectacion_tipo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    descripcion VARCHAR(255) NOT NULL,
    letra VARCHAR(1) NOT NULL,
    porcentaje NUMERIC(5,2) NOT NULL
);

-- Module.java
CREATE TABLE modules (
    id_modulo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(150),
    icon VARCHAR(100),
    route VARCHAR(255),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    display_order INTEGER NOT NULL DEFAULT 0
);

-- ============================================================
-- 3. RBAC
-- ============================================================

-- Permission.java (@JoinColumn(name = "id_modulo"))
CREATE TABLE permissions (
    id_permiso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(100) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(150),
    action VARCHAR(30) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    id_modulo BIGINT NOT NULL,

    CONSTRAINT fk_permissions_module
        FOREIGN KEY (id_modulo)
        REFERENCES modules(id_modulo)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

-- Role.permissions -> @JoinTable(name="role_permissions",
--   joinColumns=id_rol, inverseJoinColumns=id_permiso)
CREATE TABLE role_permissions (
    id_rol BIGINT NOT NULL,
    id_permiso BIGINT NOT NULL,

    PRIMARY KEY (id_rol, id_permiso),

    CONSTRAINT fk_role_permissions_role
        FOREIGN KEY (id_rol)
        REFERENCES roles(id_rol)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_role_permissions_permission
        FOREIGN KEY (id_permiso)
        REFERENCES permissions(id_permiso)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

-- User.roles -> @JoinTable(name="user_roles", joinColumns=id_usuario,
--   inverseJoinColumns=id_rol, uniqueConstraints=@UniqueConstraint(
--   name="uk_user_single_role", columnNames="id_usuario"))
-- El UNIQUE(id_usuario) es real: cada usuario solo puede tener UN rol.
CREATE TABLE user_roles (
    id_usuario BIGINT NOT NULL,
    id_rol BIGINT NOT NULL,

    PRIMARY KEY (id_usuario, id_rol),

    CONSTRAINT uk_user_single_role UNIQUE (id_usuario),

    CONSTRAINT fk_user_roles_user
        FOREIGN KEY (id_usuario)
        REFERENCES users(id_usuario)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_user_roles_role
        FOREIGN KEY (id_rol)
        REFERENCES roles(id_rol)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

-- PasswordResetToken.java (@JoinColumn(name = "id_usuario"))
CREATE TABLE password_reset_tokens (
    id_token BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token VARCHAR(255) NOT NULL UNIQUE,
    id_usuario BIGINT NOT NULL,
    expiry_date TIMESTAMP NOT NULL,
    used BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_password_reset_tokens_user
        FOREIGN KEY (id_usuario)
        REFERENCES users(id_usuario)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

-- ============================================================
-- 4. CLIENTES / PROVEEDORES
-- ============================================================

-- Cliente.java
CREATE TABLE clientes (
    id_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_tipo_codigo VARCHAR(20) NOT NULL,
    numero_documento VARCHAR(20) NOT NULL UNIQUE,
    razon_social VARCHAR(150) NOT NULL,
    direccion VARCHAR(255),
    telefono VARCHAR(30),
    email VARCHAR(150),

    CONSTRAINT fk_clientes_documento_tipo
        FOREIGN KEY (documento_tipo_codigo)
        REFERENCES documento_tipos(codigo)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

-- Proveedor.java
CREATE TABLE proveedores (
    id_proveedor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_tipo_codigo VARCHAR(20) NOT NULL,
    numero_documento VARCHAR(20) NOT NULL UNIQUE,
    razon_social VARCHAR(150) NOT NULL,
    direccion VARCHAR(255),
    telefono VARCHAR(30),
    email VARCHAR(150),

    CONSTRAINT fk_proveedores_documento_tipo
        FOREIGN KEY (documento_tipo_codigo)
        REFERENCES documento_tipos(codigo)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

-- ============================================================
-- 5. MASCOTAS
-- ============================================================

-- Pet.java (tabla física "pets", @JoinColumn(name = "id_cliente"))
CREATE TABLE pets (
    id_mascota BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    especie VARCHAR(80) NOT NULL,
    raza VARCHAR(80),
    edad INTEGER,
    id_cliente BIGINT NOT NULL,

    CONSTRAINT fk_pets_cliente
        FOREIGN KEY (id_cliente)
        REFERENCES clientes(id_cliente)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

-- ============================================================
-- 6. CITAS
-- fecha_hora es TIMESTAMP porque Appointment.java usa LocalDateTime.
-- id_veterinario apunta a users(id_usuario). Es nullable porque el
-- @JoinColumn de Appointment.java no declara nullable=false.
-- ============================================================

CREATE TABLE appointments (
    id_cita BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_mascota BIGINT NOT NULL,
    id_cliente BIGINT NOT NULL,
    id_veterinario BIGINT,
    fecha_hora TIMESTAMP NOT NULL,
    motivo VARCHAR(255) NOT NULL,

    CONSTRAINT fk_appointments_mascota
        FOREIGN KEY (id_mascota)
        REFERENCES pets(id_mascota)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_appointments_cliente
        FOREIGN KEY (id_cliente)
        REFERENCES clientes(id_cliente)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_appointments_veterinario
        FOREIGN KEY (id_veterinario)
        REFERENCES users(id_usuario)
        ON UPDATE CASCADE
        ON DELETE SET NULL
);

-- ============================================================
-- 7. HISTORIAL CLÍNICO
-- ============================================================

-- HistorialMascota.java (@JoinColumn id_mascota / id_cita)
CREATE TABLE historial_mascotas (
    id_historial BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_mascota BIGINT NOT NULL,
    id_cita BIGINT,
    titulo VARCHAR(150) NOT NULL,
    detalle VARCHAR(1500) NOT NULL,
    diagnostico VARCHAR(500),
    tratamiento VARCHAR(500),
    fecha_registro DATE NOT NULL,
    fecha_expiracion DATE NOT NULL,
    archivo_original VARCHAR(255),
    archivo_guardado VARCHAR(255),
    archivo_tipo VARCHAR(120),
    archivo_tamanio BIGINT,

    CONSTRAINT fk_historial_mascota
        FOREIGN KEY (id_mascota)
        REFERENCES pets(id_mascota)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_historial_cita
        FOREIGN KEY (id_cita)
        REFERENCES appointments(id_cita)
        ON UPDATE CASCADE
        ON DELETE SET NULL
);

-- ============================================================
-- 8. PRODUCTOS
-- ============================================================

-- Producto.java (@JoinColumn id_unidad / id_afectacion_tipo)
CREATE TABLE productos (
    id_producto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    descripcion VARCHAR(500),
    id_unidad BIGINT NOT NULL,
    id_afectacion_tipo BIGINT NOT NULL,
    precio_unitario NUMERIC(12,2) NOT NULL,
    stock INTEGER NOT NULL,
    imagen VARCHAR(255),

    CONSTRAINT fk_productos_unidad
        FOREIGN KEY (id_unidad)
        REFERENCES units(id_unidad)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_productos_afectacion
        FOREIGN KEY (id_afectacion_tipo)
        REFERENCES afectacion_tipos(id_afectacion_tipo)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_productos_precio CHECK (precio_unitario >= 0),
    CONSTRAINT chk_productos_stock CHECK (stock >= 0)
);

-- ============================================================
-- 9. COMPROBANTES
-- ============================================================

-- ComprobanteSerie.java
CREATE TABLE comprobante_series (
    id_serie BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comprobante_tipo_codigo VARCHAR(20) NOT NULL,
    serie VARCHAR(10) NOT NULL,
    correlativo INTEGER NOT NULL DEFAULT 0,

    CONSTRAINT fk_comprobante_series_tipo
        FOREIGN KEY (comprobante_tipo_codigo)
        REFERENCES comprobante_tipos(codigo)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_comprobante_series_correlativo CHECK (correlativo >= 0)
);

-- ============================================================
-- 10. COMPRAS  (Compra.java)
-- Incluye subtotal / igv / total (total = subtotal + igv).
-- ============================================================

CREATE TABLE compras (
    id_compra BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero VARCHAR(20) NOT NULL UNIQUE,
    fecha DATE NOT NULL,
    id_proveedor BIGINT NOT NULL,
    comprobante_tipo_codigo VARCHAR(20) NOT NULL,
    forma_pago VARCHAR(30) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'registrada',
    subtotal NUMERIC(12,2) NOT NULL DEFAULT 0,
    igv NUMERIC(12,2) NOT NULL DEFAULT 0,
    total NUMERIC(12,2) NOT NULL DEFAULT 0,

    CONSTRAINT fk_compras_proveedor
        FOREIGN KEY (id_proveedor)
        REFERENCES proveedores(id_proveedor)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_compras_comprobante_tipo
        FOREIGN KEY (comprobante_tipo_codigo)
        REFERENCES comprobante_tipos(codigo)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_compras_subtotal CHECK (subtotal >= 0),
    CONSTRAINT chk_compras_igv CHECK (igv >= 0),
    CONSTRAINT chk_compras_total CHECK (total >= 0)
);

-- ============================================================
-- 10.1 DETALLE DE COMPRAS  (CompraDetalle.java)
-- Un producto por línea; "subtotal" es columna calculada por Postgres.
-- ============================================================

CREATE TABLE compra_detalles (
    id_detalle_compra BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compra BIGINT NOT NULL,
    id_producto BIGINT NOT NULL,
    cantidad INTEGER NOT NULL,
    precio_unitario NUMERIC(12,2) NOT NULL,
    subtotal NUMERIC(12,2) NOT NULL
        GENERATED ALWAYS AS
        (cantidad * precio_unitario) STORED,

    CONSTRAINT fk_compra_detalles_compra
        FOREIGN KEY (id_compra)
        REFERENCES compras(id_compra)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_compra_detalles_producto
        FOREIGN KEY (id_producto)
        REFERENCES productos(id_producto)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_compra_detalles_cantidad CHECK (cantidad > 0),
    CONSTRAINT chk_compra_detalles_precio CHECK (precio_unitario >= 0),

    CONSTRAINT uq_compra_producto UNIQUE (id_compra, id_producto)
);

-- ============================================================
-- 11. VENTAS  (Venta.java)
-- ============================================================

CREATE TABLE ventas (
    id_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero VARCHAR(20) NOT NULL UNIQUE,
    fecha DATE NOT NULL,
    id_cliente BIGINT NOT NULL,
    forma_pago VARCHAR(30) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'registrada',
    subtotal NUMERIC(12,2) NOT NULL DEFAULT 0,
    igv NUMERIC(12,2) NOT NULL DEFAULT 0,
    total NUMERIC(12,2) NOT NULL DEFAULT 0,

    CONSTRAINT fk_ventas_cliente
        FOREIGN KEY (id_cliente)
        REFERENCES clientes(id_cliente)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_ventas_subtotal CHECK (subtotal >= 0),
    CONSTRAINT chk_ventas_igv CHECK (igv >= 0),
    CONSTRAINT chk_ventas_total CHECK (total >= 0)
);

-- ============================================================
-- 11.1 DETALLE DE VENTAS
-- Todavía no existe VentaDetalle.java (Ventas sigue usando un total
-- manual, igual que Compras antes de esta mejora). Se crea la tabla ya
-- alineada con la convención de nombres para cuando se replique en
-- Ventas el mismo cambio que se hizo en Compras; hoy no la usa ningún
-- repositorio y no interfiere con nada.
-- ============================================================

CREATE TABLE venta_detalles (
    id_detalle_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venta BIGINT NOT NULL,
    id_producto BIGINT NOT NULL,
    cantidad INTEGER NOT NULL,
    precio_unitario NUMERIC(12,2) NOT NULL,
    subtotal NUMERIC(12,2) NOT NULL
        GENERATED ALWAYS AS
        (cantidad * precio_unitario) STORED,

    CONSTRAINT fk_venta_detalles_venta
        FOREIGN KEY (id_venta)
        REFERENCES ventas(id_venta)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_venta_detalles_producto
        FOREIGN KEY (id_producto)
        REFERENCES productos(id_producto)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_venta_detalles_cantidad CHECK (cantidad > 0),
    CONSTRAINT chk_venta_detalles_precio CHECK (precio_unitario >= 0),

    CONSTRAINT uq_venta_producto UNIQUE (id_venta, id_producto)
);

