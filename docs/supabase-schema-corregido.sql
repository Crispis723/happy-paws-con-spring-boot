-- HAPPY PAWS - SUPABASE
-- ESQUEMA 100% ALINEADO CON LAS ENTIDADES JPA DEL PROYECTO (verificado
-- columna por columna contra cada @Column / @JoinColumn / @JoinTable de
-- src/main/java/com/Happypaws/demo/model, agosto 2026).
--
-- Corrige respecto al script anterior:
--   * Todas las PK usan el nombre real de columna de cada entidad
--     (id_usuario, id_rol, id_modulo, id_permiso, id_cliente, id_proveedor,
--     id_mascota, id_cita, id_historial, id_producto, id_serie, id_compra,
--     id_detalle_compra, id_venta, id_detalle_venta, id_configuracion,
--     id_documento_tipo, id_comprobante_tipo, id_unidad, id_afectacion_tipo,
--     id_token) en vez de "id" genérico.
--   * FKs con el nombre real que usa cada @JoinColumn (id_modulo, id_rol,
--     id_permiso, id_usuario, id_mascota, id_cliente, id_veterinario,
--     id_cita, id_unidad, id_afectacion_tipo, id_proveedor, id_producto,
--     id_compra) en vez de module_id/role_id/permission_id/user_id/pet_id/
--     cliente_id/proveedor_id/producto_id.
--   * Se agregan las columnas "subtotal" e "igv" en "compras" (Compra.java).
--   * Se agrega la tabla "compra_detalles" (CompraDetalle.java), incluyendo
--     su columna "subtotal" GENERATED ALWAYS AS (cantidad * precio_unitario).
--   * Se agrega "venta_detalles" con la misma forma, lista para cuando el
--     módulo de Ventas reciba la misma mejora (aún no hay entidad Java para
--     ella, así que hoy no la usa ningún repositorio, pero no estorba).
--   * user_roles conserva la restricción real UNIQUE(id_usuario) definida en
--     User.java (@UniqueConstraint(name="uk_user_single_role")): cada
--     usuario solo puede tener UN rol.
--
-- IMPORTANTE: este script reconstruye las tablas del sistema.
-- Úsalo sobre una BD nueva/de desarrollo o haz backup primero.
-- ============================================================

BEGIN;

-- ============================================================
